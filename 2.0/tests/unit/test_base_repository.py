"""
Unit tests for BaseRepository and ResilientRepository.

Tests:
- Pooled connection management
- Error handling utilities
- The DELETE helper
- Failure tracking and recovery

Six tests were deleted rather than ported, and it is worth saying which:
`test_init_with_path_string`, `test_init_with_path_object`,
`test_init_with_custom_timeout` and `test_get_connection_creates_direct_connection`
all asserted the direct-`sqlite3.connect(db_path)` fallback, which no longer
exists — there is no path to fall back to and no safe way to fabricate a
Postgres database on connect. `test_get_connection_uses_pool_when_available`
mocked `pool.get_connection()`, a method name that only existed on the SQLite
pool. Their replacements below exercise the helpers against a real server
instead of asserting the shape of the plumbing.
"""

from unittest.mock import patch

import pytest

from src.domain.errors import Err, ErrorCode, Ok
from src.infrastructure.database.repositories.base_repository import (
    BaseRepository,
    ResilientRepository,
)


class ConcreteRepository(BaseRepository):
    """Concrete implementation for testing BaseRepository."""

    def create_test_table(self):
        """Create a test table."""
        with self._get_connection() as conn:
            conn.execute(
                "CREATE TABLE IF NOT EXISTS test "
                "(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text)"
            )
            conn.commit()

    def insert_item(self, name: str):
        with self._get_connection() as conn:
            conn.execute("INSERT INTO test (name) VALUES (%s)", (name,))
            conn.commit()

    def get_names(self):
        with self._get_connection() as conn:
            return [row.name for row in conn.execute("SELECT name FROM test ORDER BY id")]


@pytest.mark.pg
class TestBaseRepository:
    """Tests for BaseRepository against a throwaway Postgres schema."""

    def test_uses_the_pool_it_was_given(self, pg_pool):
        """A repository must never silently reach past its injected pool --
        that is what made the SQLite direct-connection fallback dangerous."""
        repo = ConcreteRepository(pool=pg_pool)
        assert repo.pool is pg_pool
        with repo._get_connection() as conn:
            assert conn.execute("SELECT 1").fetchone()[0] == 1

    def test_defaults_to_the_process_pool_lazily(self):
        """Constructing a repository must not open a connection. This is why
        `pool` is a property, not resolved in __init__: importing or building
        a repository in a test with no database must not fail."""
        repo = ConcreteRepository()
        assert repo._pool is None

    def test_db_error_returns_err_with_dberror_code(self):
        import psycopg
        repo = ConcreteRepository()
        error = psycopg.OperationalError("disk full")

        result = repo._db_error(error, "insert")

        assert isinstance(result, (Ok, Err))
        assert result.is_err
        assert result.error.code == ErrorCode.DBERROR
        assert "disk full" in result.error.message

    def test_execute_delete_returns_count(self, pg_pool):
        repo = ConcreteRepository(pool=pg_pool)
        repo.create_test_table()
        repo.insert_item("delete_me")
        repo.insert_item("keep_me")

        result = repo._execute_delete(
            "DELETE FROM test WHERE name = %s",
            ("delete_me",),
        )

        assert isinstance(result, (Ok, Err))
        assert result.is_ok
        assert result.value == 1
        assert repo.get_names() == ["keep_me"]

    def test_a_bad_query_returns_err_not_a_raise(self, pg_pool):
        """The reason every `except sqlite3.Error` had to become
        `except psycopg.Error`: psycopg.Error does NOT inherit sqlite3.Error,
        so the untouched handlers would have stopped catching and the
        Result/Err contract would have broken into a bare exception."""
        repo = ConcreteRepository(pool=pg_pool)

        result = repo._execute_delete("DELETE FROM no_such_table")

        assert result.is_err
        assert result.error.code == ErrorCode.DBERROR


class TestResilientRepository:
    """Tests for ResilientRepository. Pure failure tracking, no database."""

    def test_init_sets_failure_tracking(self):
        repo = ResilientRepository(max_failures=5)

        assert repo.failure_count == 0
        assert repo.max_failures == 5
        assert repo.is_healthy is True

    def test_record_success_resets_counter(self):
        repo = ResilientRepository()
        repo.failure_count = 5

        repo._record_success()

        assert repo.failure_count == 0

    def test_record_failure_increments_counter(self):
        repo = ResilientRepository(max_failures=5)

        repo._record_failure(Exception("test"), "operation")

        assert repo.failure_count == 1
        assert repo.is_healthy is True

    def test_record_failure_logs_critical_at_threshold(self):
        repo = ResilientRepository(max_failures=3)
        repo.failure_count = 2  # One below threshold

        with patch("src.infrastructure.database.repositories.base_repository.logger") as mock_logger:
            repo._record_failure(Exception("db crash"), "write data")

            mock_logger.critical.assert_called_once()
            assert "3 consecutive times" in mock_logger.critical.call_args[0][0]

    def test_is_healthy_true_below_threshold(self):
        repo = ResilientRepository(max_failures=5)
        repo.failure_count = 4

        assert repo.is_healthy is True

    def test_is_healthy_false_at_threshold(self):
        repo = ResilientRepository(max_failures=5)
        repo.failure_count = 5

        assert repo.is_healthy is False

    def test_inherits_from_base_repository(self):
        repo = ResilientRepository()

        assert isinstance(repo, BaseRepository)
        assert hasattr(repo, "_get_connection")
        assert hasattr(repo, "_db_error")
        assert hasattr(repo, "_execute_delete")
