"""Unit tests for scripts/resolve_ambiguous_moves.py.

Covers the resolution contract: Yahoo is the authority for which date is the real
earnings event, stored reaction-day price bars are the corroborating second source,
and any disagreement leaves the cluster untouched rather than guessed at.
"""

from datetime import date

import pytest

from common.db import connect  # noqa: E402
from scripts.resolve_ambiguous_moves import (  # noqa: E402
    MIN_CONTRADICTION_MOVE_PCT,
    PRICE_CONTRADICTION_RATIO,
    find_clusters,
    resolve_clusters,
)
from src.domain.errors import Err, Ok  # noqa: E402
from src.domain.types import EarningsTiming  # noqa: E402

pytestmark = pytest.mark.pg


class _FakeYahoo:
    """Stands in for YahooFinanceEarnings.

    Mirrors the real contract: the answer depends on the candidate dates asked
    about, not just the ticker — a ticker reports every quarter, so the same
    ticker legitimately returns different dates for different clusters.
    """

    def __init__(self, dates):
        self.dates = dates          # {ticker: "YYYY-MM-DD" | [dates] | None}
        self.calls = []

    def get_earnings_date_near(self, ticker, reference_dates):
        self.calls.append((ticker, tuple(d.isoformat() for d in reference_dates)))
        d = self.dates.get(ticker)
        if d is None:
            return Err("unavailable")
        known = [d] if isinstance(d, str) else list(d)
        nearest = min(
            (date.fromisoformat(k) for k in known),
            key=lambda k: min(abs((k - ref).days) for ref in reference_dates),
        )
        return Ok((nearest, EarningsTiming.AMC))


def _create_db(schema):
    """Tables in the test's throwaway schema. `pg_schema` sets PGOPTIONS, so
    the script under test connects into the same one without patching."""
    with connect() as conn:
        conn.execute("""
            CREATE TABLE historical_moves (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ticker text NOT NULL,
                earnings_date date NOT NULL,
                gap_move_pct double precision,
                close_move_pct double precision
            )
        """)
        conn.execute("""
            CREATE TABLE earnings_calendar (
                ticker text NOT NULL,
                earnings_date date NOT NULL,
                timing text DEFAULT 'AMC',
                confirmed boolean DEFAULT true,
                PRIMARY KEY (ticker, earnings_date)
            )
        """)
        conn.commit()
    return schema


def _add(db, ticker, d, gap, close=None, calendar=True):
    with connect() as conn:
        conn.execute(
            "INSERT INTO historical_moves (ticker, earnings_date, gap_move_pct, close_move_pct)"
            " VALUES (%s,%s,%s,%s)",
            (ticker, d, gap, close if close is not None else gap),
        )
        if calendar:
            conn.execute(
                "INSERT INTO earnings_calendar (ticker, earnings_date) VALUES (%s,%s)"
                " ON CONFLICT (ticker, earnings_date) DO NOTHING",
                (ticker, d),
            )
        conn.commit()


def _dates(db, ticker, table="historical_moves"):
    with connect() as conn:
        rows = conn.execute(
            f"SELECT earnings_date FROM {table} WHERE ticker=%s ORDER BY earnings_date",
            (ticker,),
        ).fetchall()
    # earnings_date is a real date column now; the assertions compare ISO text.
    return [r[0].isoformat() for r in rows]


class TestFindClusters:

    def test_groups_near_dates(self, pg_schema):
        db = _create_db(pg_schema)
        _add(db, "META", "2026-01-28", 10.27)
        _add(db, "META", "2026-02-02", -0.27)
        clusters = find_clusters()
        assert len(clusters) == 1
        assert len(clusters[0]["rows"]) == 2

    def test_does_not_group_separate_quarters(self, pg_schema):
        """A 90-day quarterly cadence must never look like one event."""
        db = _create_db(pg_schema)
        _add(db, "AAPL", "2026-01-28", 3.0)
        _add(db, "AAPL", "2026-04-28", 4.0)
        assert find_clusters() == []

    def test_groups_three_row_cluster(self, pg_schema):
        db = _create_db(pg_schema)
        for d, g in [("2026-08-24", -0.69), ("2026-08-25", -2.0), ("2026-08-26", 23.61)]:
            _add(db, "OKTA", d, g)
        clusters = find_clusters()
        assert len(clusters) == 1
        assert len(clusters[0]["rows"]) == 3

    def test_respects_ticker_filter(self, pg_schema):
        db = _create_db(pg_schema)
        _add(db, "META", "2026-01-28", 10.0)
        _add(db, "META", "2026-02-02", -0.3)
        _add(db, "ORCL", "2025-12-10", -14.5)
        _add(db, "ORCL", "2025-12-18", 2.4)
        clusters = find_clusters(tickers=["ORCL"])
        assert len(clusters) == 1
        assert clusters[0]["ticker"] == "ORCL"


class TestResolution:

    def test_yahoo_match_resolves_and_deletes_both_tables(self, pg_schema):
        db = _create_db(pg_schema)
        _add(db, "META", "2026-01-28", 10.27)
        _add(db, "META", "2026-02-02", -0.27)

        res = resolve_clusters(_FakeYahoo({"META": "2026-01-28"}),
                               dry_run=False)

        assert len(res["resolved"]) == 1
        assert res["moves_deleted"] == 1
        assert res["calendar_deleted"] == 1
        assert _dates(db, "META") == ["2026-01-28"]
        assert _dates(db, "META", "earnings_calendar") == ["2026-01-28"]

    def test_dry_run_deletes_nothing(self, pg_schema):
        db = _create_db(pg_schema)
        _add(db, "META", "2026-01-28", 10.27)
        _add(db, "META", "2026-02-02", -0.27)

        res = resolve_clusters(_FakeYahoo({"META": "2026-01-28"}),
                               dry_run=True)

        assert len(res["resolved"]) == 1
        assert res["moves_deleted"] == 1          # reported, not applied
        assert _dates(db, "META") == ["2026-01-28", "2026-02-02"]

    def test_three_row_cluster_keeps_only_yahoo_date(self, pg_schema):
        db = _create_db(pg_schema)
        for d, g in [("2026-08-24", -0.69), ("2026-08-25", -2.0), ("2026-08-26", 23.61)]:
            _add(db, "OKTA", d, g)

        res = resolve_clusters(_FakeYahoo({"OKTA": "2026-08-26"}),
                               dry_run=False)

        assert res["moves_deleted"] == 2
        assert _dates(db, "OKTA") == ["2026-08-26"]

    def test_yahoo_unavailable_leaves_cluster(self, pg_schema):
        db = _create_db(pg_schema)
        _add(db, "META", "2026-01-28", 10.27)
        _add(db, "META", "2026-02-02", -0.27)

        res = resolve_clusters(_FakeYahoo({"META": None}),
                               dry_run=False)

        assert res["resolved"] == []
        assert len(res["unresolved"]) == 1
        assert _dates(db, "META") == ["2026-01-28", "2026-02-02"]

    def test_yahoo_date_matching_no_candidate_leaves_cluster(self, pg_schema):
        """A third date means we do not understand the cluster — do not guess."""
        db = _create_db(pg_schema)
        _add(db, "META", "2026-01-28", 10.27)
        _add(db, "META", "2026-02-02", -0.27)

        res = resolve_clusters(_FakeYahoo({"META": "2026-03-15"}),
                               dry_run=False)

        assert res["resolved"] == []
        assert "matches 0" in res["unresolved"][0]["reason"]
        assert _dates(db, "META") == ["2026-01-28", "2026-02-02"]

    def test_price_contradiction_blocks_deletion(self, pg_schema):
        """Yahoo picking the flat day while another moved hugely = disagreement."""
        db = _create_db(pg_schema)
        _add(db, "RBLX", "2026-04-30", -23.31)
        _add(db, "RBLX", "2026-05-07", 1.21)

        res = resolve_clusters(_FakeYahoo({"RBLX": "2026-05-07"}),
                               dry_run=False)

        assert res["resolved"] == []
        assert "price contradicts" in res["unresolved"][0]["reason"]
        assert _dates(db, "RBLX") == ["2026-04-30", "2026-05-07"]

    def test_mild_price_difference_does_not_block(self, pg_schema):
        """Only a decisive contradiction blocks; ordinary noise must not."""
        db = _create_db(pg_schema)
        _add(db, "T", "2026-01-28", 1.58)
        _add(db, "T", "2026-02-02", -0.72)

        res = resolve_clusters(_FakeYahoo({"T": "2026-02-02"}),
                               dry_run=False)

        ratio = 1.58 / 0.72
        assert ratio < PRICE_CONTRADICTION_RATIO
        assert len(res["resolved"]) == 1
        assert _dates(db, "T") == ["2026-02-02"]

    def test_two_clusters_on_one_ticker_both_resolve(self, pg_schema):
        """A ticker reports quarterly, so it can have several damaged clusters.

        Regression guard: caching one Yahoo answer per *ticker* handed the second
        cluster the first cluster's date, which matched nothing, silently
        stranding every cluster after the first as unresolved. The lookup is
        per-cluster because the question is "nearest to THESE dates".
        """
        db = _create_db(pg_schema)
        _add(db, "UNH", "2026-01-27", -16.4)
        _add(db, "UNH", "2026-02-04", -0.76)
        _add(db, "UNH", "2026-04-21", 1.41)
        _add(db, "UNH", "2026-04-29", -0.6)

        fake = _FakeYahoo({"UNH": ["2026-01-27", "2026-04-21"]})
        res = resolve_clusters(fake, dry_run=False)

        assert len(res["resolved"]) == 2
        assert res["moves_deleted"] == 2
        assert _dates(db, "UNH") == ["2026-01-27", "2026-04-21"]

    def test_same_cluster_is_not_looked_up_twice(self, pg_schema):
        """Caching still applies within a cluster."""
        db = _create_db(pg_schema)
        _add(db, "META", "2026-01-28", 10.27)
        _add(db, "META", "2026-02-02", -0.27)

        fake = _FakeYahoo({"META": "2026-01-28"})
        resolve_clusters(fake, dry_run=True)

        assert len(fake.calls) == 1


class TestPriceVetoFloor:
    """The price veto needs a reaction-sized rival move, not just a big ratio."""

    def test_noise_level_rival_does_not_veto(self, pg_schema):
        """MTB-shaped case: 0.03% vs 0.54% is 16x but neither is an earnings move."""
        db = _create_db(pg_schema)
        _add(db, "MTB", "2026-01-16", 0.03)
        _add(db, "MTB", "2026-01-19", 0.54)

        res = resolve_clusters(_FakeYahoo({"MTB": "2026-01-16"}),
                               dry_run=False)

        assert len(res["resolved"]) == 1
        assert _dates(db, "MTB") == ["2026-01-16"]

    def test_reaction_sized_rival_still_vetoes(self, pg_schema):
        """Above the floor the veto must still fire — the guard is not disabled."""
        db = _create_db(pg_schema)
        _add(db, "RBLX", "2026-04-30", -23.31)
        _add(db, "RBLX", "2026-05-07", 1.21)

        res = resolve_clusters(_FakeYahoo({"RBLX": "2026-05-07"}),
                               dry_run=False)

        assert res["resolved"] == []
        assert _dates(db, "RBLX") == ["2026-04-30", "2026-05-07"]

    def test_floor_boundary_is_inclusive_of_veto(self, pg_schema):
        """A rival exactly at the floor counts as reaction-sized and vetoes."""
        db = _create_db(pg_schema)
        _add(db, "XYZ", "2026-01-16", 0.10)
        _add(db, "XYZ", "2026-01-19", MIN_CONTRADICTION_MOVE_PCT)

        res = resolve_clusters(_FakeYahoo({"XYZ": "2026-01-16"}),
                               dry_run=False)

        assert res["resolved"] == []
        assert len(_dates(db, "XYZ")) == 2


class TestDryRunReportsRealBlastRadius:
    """A dry run must predict exactly what --execute will delete, in both tables."""

    def test_dry_run_counts_calendar_rows(self, pg_schema):
        db = _create_db(pg_schema)
        _add(db, "META", "2026-01-28", 10.27)
        _add(db, "META", "2026-02-02", -0.27)

        res = resolve_clusters(_FakeYahoo({"META": "2026-01-28"}),
                               dry_run=True)

        assert res["moves_deleted"] == 1
        assert res["calendar_deleted"] == 1, "dry run under-reported calendar impact"

    def test_dry_run_matches_execute_exactly(self, pg_schema):
        """The two modes must agree on both counts, or the dry run is misleading."""
        db_dry = _create_db(pg_schema)
        for d, g in [("2026-08-24", -0.69), ("2026-08-25", -2.0), ("2026-08-26", 23.61)]:
            _add(db_dry, "OKTA", d, g)
        _add(db_dry, "META", "2026-01-28", 10.27)
        _add(db_dry, "META", "2026-02-02", -0.27)

        yahoo = {"OKTA": "2026-08-26", "META": "2026-01-28"}
        dry = resolve_clusters(_FakeYahoo(yahoo), dry_run=True)
        live = resolve_clusters(_FakeYahoo(yahoo), dry_run=False)

        assert dry["moves_deleted"] == live["moves_deleted"]
        assert dry["calendar_deleted"] == live["calendar_deleted"]

    def test_dry_run_counts_zero_when_calendar_row_absent(self, pg_schema):
        """No calendar row for the loser -> nothing to count, and none invented."""
        db = _create_db(pg_schema)
        _add(db, "META", "2026-01-28", 10.27)
        _add(db, "META", "2026-02-02", -0.27, calendar=False)

        res = resolve_clusters(_FakeYahoo({"META": "2026-01-28"}),
                               dry_run=True)

        assert res["moves_deleted"] == 1
        assert res["calendar_deleted"] == 0
