def test_vrp_is_not_constant_across_events(db):
    """Regression guard for the bug that motivated this work.

    services/backtest/runner.py hardcoded implied = avg_move * 1.4, making VRP
    identically 1.4 and unable to discriminate between events at all.
    """
    conn = connect()
    with conn.cursor() as cur:
        cur.executemany(
            "INSERT INTO historical_moves "
            "(ticker, earnings_date, close_move_pct, intraday_move_pct, "
            "pre_earnings_straddle_pct, ern_iv_effect) VALUES (%s,%s,%s,%s,%s,%s)",
            [("AA", f"202{y}-03-01", 2.0, 2.0, 2.0, None) for y in range(0, 5)]
            + [("AA", "2025-06-01", 1.0, 1.0, 9.0, None)],
        )
    conn.commit()
    conn.close()
    assert len({round(e["vrp"], 6) for e in load_events()}) > 1


def test_baseline_selects_only_the_vrp_denominator(pg_schema):
    """Both VRP conventions stay reproducible, and the OUTCOME never moves.

    The live system's denominator is close_move_pct since the 2026-09
    migration; intraday_move_pct is what intraday-era studies and the A/B
    evaluator still grade on, so it must stay reproducible too. Critically, an
    A/B that varied the outcome alongside the denominator would not be
    comparing denominators at all -- so `actual`/`crushed`/`edge` must be
    identical across baselines.
    """
    conn = connect()
    conn.execute(MOVES_DDL)
    # close moves 4.0 flat, intraday 2.0 flat -> different denominators.
    rows = [("MU", f"2024-0{m}-15", 4.0, 2.0, 6.0, None) for m in range(1, 6)]
    with conn.cursor() as cur:
        cur.executemany(
            "INSERT INTO historical_moves (ticker, earnings_date, close_move_pct, "
            "intraday_move_pct, pre_earnings_straddle_pct, ern_iv_effect) "
            "VALUES (%s,%s,%s,%s,%s,%s)", rows
        )
    conn.commit()
    conn.close()

    target = date(2024, 5, 15)
    close = next(e for e in load_events(baseline="close")
                 if e["earnings_date"] == target)
    intraday = next(e for e in load_events(baseline="intraday")
                    if e["earnings_date"] == target)

    # Denominator varies...
    assert close["mean_prior"] == pytest.approx(4.0)
    assert intraday["mean_prior"] == pytest.approx(2.0)
    assert close["vrp"] == pytest.approx(6.0 / 4.0)
    assert intraday["vrp"] == pytest.approx(6.0 / 2.0)

    # ...but the outcome is held fixed at the gap-inclusive close move.
    assert close["actual"] == intraday["actual"] == pytest.approx(4.0)
    assert close["crushed"] == intraday["crushed"] == 1
    assert close["edge"] == intraday["edge"] == pytest.approx(2.0)


def test_baseline_defaults_to_close_matching_the_live_system():
    """The live calculator grades on close-to-close since the 2026-09 migration. The
    fixtures here make intraday equal close, so the default is read off the signature;
    test_baseline_selects_only_the_vrp_denominator proves the column each value maps to."""
    import inspect
    assert inspect.signature(load_events).parameters["baseline"].default == "close"


