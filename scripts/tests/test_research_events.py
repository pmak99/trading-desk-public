MOVES_DDL = """CREATE TABLE historical_moves (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ticker text,
    earnings_date date, close_move_pct double precision,
    intraday_move_pct double precision,
    pre_earnings_straddle_pct double precision,
    ern_iv_effect double precision)"""


@pytest.fixture
def db(pg_schema):
    conn = connect()
    conn.execute(MOVES_DDL)
    # intraday mirrors close here so the default-baseline tests below read
    # naturally; the baseline-selection test uses its own fixture where they
    # differ.
    rows = [
        ("MU", "2024-01-15", -4.0, -4.0, 6.0, 1.2),
        ("MU", "2024-04-15", 3.0, 3.0, 6.0, 1.4),
        ("MU", "2024-07-15", -5.0, -5.0, 6.0, 1.1),
        ("MU", "2024-10-15", 2.0, 2.0, 6.0, 1.3),
        ("MU", "2025-01-15", 8.0, 8.0, 6.0, 2.1),   # target: prior mean |move| = 3.5
        ("NS", "2025-01-15", 2.0, 2.0, None, None),  # no straddle -> skipped
    ]
    with conn.cursor() as cur:
        cur.executemany("INSERT INTO historical_moves "
                        "(ticker, earnings_date, close_move_pct, intraday_move_pct, "
                        "pre_earnings_straddle_pct, ern_iv_effect) "
                        "VALUES (%s,%s,%s,%s,%s,%s)", rows)
    conn.commit()
    conn.close()
    return pg_schema


