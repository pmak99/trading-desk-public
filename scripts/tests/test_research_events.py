def test_prior_crush_rate_is_point_in_time(pg_schema):
    """Trailing crush frequency must use only strictly-earlier events."""
    conn = connect()
    conn.execute(MOVES_DDL)
    # 4 priors: 3 crushed (straddle 6 > move 2), 1 not (straddle 6 < move 9).
    rows = [
        ("MU", "2024-01-15", 2.0, 2.0, 6.0, None),
        ("MU", "2024-04-15", 2.0, 2.0, 6.0, None),
        ("MU", "2024-07-15", 2.0, 2.0, 6.0, None),
        ("MU", "2024-10-15", 9.0, 9.0, 6.0, None),
        ("MU", "2025-01-15", 1.0, 1.0, 6.0, 2.5),
    ]
    with conn.cursor() as cur:
        cur.executemany(
            "INSERT INTO historical_moves (ticker, earnings_date, close_move_pct, "
            "intraday_move_pct, pre_earnings_straddle_pct, ern_iv_effect) "
            "VALUES (%s,%s,%s,%s,%s,%s)", rows
        )
    conn.commit()
    conn.close()

    target = next(e for e in load_events()
                  if e["earnings_date"] == date(2025, 1, 15))
    assert target["prior_crush_rate"] == pytest.approx(0.75)  # 3 of 4
    assert target["iv_effect"] == pytest.approx(2.5)


def test_prior_crush_rate_is_none_below_minimum(db):
    """Too few priors to be meaningful must yield None, not a misleading number."""
    events = load_events(min_prior=1)
    early = [e for e in events if len(e["prior_moves"]) < 3]
    assert early, "fixture should produce at least one thin-history event"
    assert all(e["prior_crush_rate"] is None for e in early)


